import com.mycompany.Model.Product;
import com.mycompany.canteeninventory.DBConnection;
import java.sql.*;
import javax.swing.JComboBox;
import javax.swing.table.DefaultTableModel;
import javax.swing.table.TableModel;

// ProductDAO = talks directly to MySQL (products table).
// NOTE: the numbers in pst.setXXX(number, value) = position of the "?" in the SQL.
public class ProductDAO {

    // =====================================================
    // CREATE: add a new product
    // Product ID and Stock Status are generated by MySQL.
    // =====================================================
    public static boolean save(Product p) {

        String sql = "INSERT INTO products "
                + "(product_name, category_id, supplier_id, unit_price, quantity) "
                + "VALUES (?, ?, ?, ?, ?)";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, p.getProductName());                 // 1 = product_name
            pst.setInt(2, Integer.parseInt(p.getCategoryID()));   // 2 = category_id

            if (p.getSupplierID() != null
                    && !p.getSupplierID().trim().isEmpty()) {
                pst.setInt(3, Integer.parseInt(p.getSupplierID())); // 3 = supplier_id
            } else {
                pst.setNull(3, Types.INTEGER);                      // 3 = supplier_id (NULL)
            }

            pst.setBigDecimal(4, new java.math.BigDecimal(p.getUnitPrice())); // 4 = unit_price
            pst.setInt(5, Integer.parseInt(p.getQuantity()));                 // 5 = quantity

            pst.executeUpdate();
            return true;

        } catch (Exception e) {
            System.out.println("Save Error: " + e.getMessage());
            return false;
        }
    }

    // =====================================================
    // READ: get ONE product by Product ID (null if not found)
    // =====================================================
    public static Product getByID(String productID) {

        String sql = "SELECT * FROM products WHERE product_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, Integer.parseInt(productID));   // 1 = product_id to search

            try (ResultSet rs = pst.executeQuery()) {

                if (rs.next()) {

                    Product p = new Product();

                    p.setProductID(rs.getString("product_id"));
                    p.setProductName(rs.getString("product_name"));
                    p.setCategoryID(rs.getString("category_id"));

                    int supplierID = rs.getInt("supplier_id");

                    if (rs.wasNull()) {
                        p.setSupplierID("");
                    } else {
                        p.setSupplierID(String.valueOf(supplierID));
                    }

                    p.setUnitPrice(rs.getString("unit_price"));
                    p.setQuantity(rs.getString("quantity"));
                    p.setStockStatus(rs.getString("stock_status"));

                    return p;
                }
            }

        } catch (Exception e) {
            System.out.println("Read Error: " + e.getMessage());
        }

        return null;
    }

    // =====================================================
    // UPDATE: change an existing product (using Product ID)
    // =====================================================
    public static boolean update(Product p) {

        String sql = "UPDATE products SET "
                + "product_name = ?, category_id = ?, supplier_id = ?, "
                + "unit_price = ?, quantity = ? "
                + "WHERE product_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, p.getProductName());                 // 1 = product_name
            pst.setInt(2, Integer.parseInt(p.getCategoryID()));   // 2 = category_id

            if (p.getSupplierID() == null
                    || p.getSupplierID().trim().isEmpty()) {
                pst.setNull(3, Types.INTEGER);                      // 3 = supplier_id (NULL)
            } else {
                pst.setInt(3, Integer.parseInt(p.getSupplierID())); // 3 = supplier_id
            }

            pst.setBigDecimal(4, new java.math.BigDecimal(p.getUnitPrice())); // 4 = unit_price
            pst.setInt(5, Integer.parseInt(p.getQuantity()));                 // 5 = quantity
            pst.setInt(6, Integer.parseInt(p.getProductID()));                // 6 = product_id (WHERE)

            return pst.executeUpdate() > 0;

        } catch (Exception e) {
            System.out.println("Update Error: " + e.getMessage());
            return false;
        }
    }

    // =====================================================
    // DELETE: remove a product by Product ID
    // Fails if it already has Stock In / Stock Out records.
    // =====================================================
    public static boolean delete(String productID) {

        String sql = "DELETE FROM products WHERE product_id = ?";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, Integer.parseInt(productID));   // 1 = product_id to delete

            return pst.executeUpdate() > 0;

        } catch (Exception e) {
            System.out.println("Delete Error: " + e.getMessage());
            return false;
        }
    }

    // =====================================================
    // DISPLAY TABLE: get ALL products for the JTable
    // =====================================================
    public static TableModel getTableData() {

        DefaultTableModel model = new DefaultTableModel();

        model.addColumn("Product ID");     // column 1
        model.addColumn("Product Name");   // column 2
        model.addColumn("Category ID");    // column 3
        model.addColumn("Supplier ID");    // column 4
        model.addColumn("Unit Price");     // column 5
        model.addColumn("Quantity");       // column 6
        model.addColumn("Stock Status");   // column 7

        String sql = "SELECT product_id, product_name, category_id, "
                + "supplier_id, unit_price, quantity, stock_status "
                + "FROM products "
                + "ORDER BY product_id";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql);
             ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getInt("product_id"),          // column 1
                    rs.getString("product_name"),     // column 2
                    rs.getInt("category_id"),         // column 3
                    rs.getString("supplier_id"),      // column 4 (getString: empty supplier stays blank)
                    rs.getBigDecimal("unit_price"),   // column 5
                    rs.getInt("quantity"),            // column 6
                    rs.getString("stock_status")      // column 7
                });
            }

        } catch (Exception e) {
            System.out.println("Table Error: " + e.getMessage());
        }

        return model;
    }

    // =====================================================
    // LOAD CATEGORIES into the Category combo box
    // =====================================================
    public static void loadCategories(JComboBox<ComboItem> combo) {

        combo.removeAllItems();
        combo.addItem(new ComboItem(0, "Select Categories"));   // default item (ID 0)

        String sql = "SELECT category_id, category_name FROM categories";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql);
             ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                combo.addItem(new ComboItem(
                        rs.getInt("category_id"),
                        rs.getString("category_name")
                ));
            }

        } catch (Exception e) {
            System.out.println("Category Error: " + e.getMessage());
        }
    }

    // =====================================================
    // LOAD SUPPLIERS into the Supplier combo box
    // =====================================================
    public static void loadSuppliers(JComboBox<ComboItem> combo) {

        combo.removeAllItems();
        combo.addItem(new ComboItem(0, "Select Supplier"));   // default item (ID 0)

        String sql = "SELECT supplier_id, supplier_name FROM suppliers";

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql);
             ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                combo.addItem(new ComboItem(
                        rs.getInt("supplier_id"),
                        rs.getString("supplier_name")
                ));
            }

        } catch (Exception e) {
            System.out.println("Supplier Error: " + e.getMessage());
        }
    }

    // =====================================================
    // DUPLICATE CHECK: does this product name already exist?
    // - not case-sensitive, ignores spaces before/after
    // - excludeId = product to skip ("" for CREATE, current ID for UPDATE)
    // =====================================================
    public static boolean nameExists(String name, String excludeId) {

        String sql = "SELECT COUNT(*) FROM products "
                + "WHERE LOWER(TRIM(product_name)) = LOWER(TRIM(?))";

        boolean hasExclude = excludeId != null && !excludeId.trim().isEmpty();

        if (hasExclude) {
            sql += " AND product_id <> ?";   // adds the 2nd ?
        }

        try (Connection con = DBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setString(1, name);   // 1 = product_name to check

            if (hasExclude) {
                pst.setInt(2, Integer.parseInt(excludeId.trim()));   // 2 = product_id to skip
            }

            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    return rs.getInt(1) > 0;   // more than 0 = name already exists
                }
            }

        } catch (Exception e) {
            System.out.println("Name Check Error: " + e.getMessage());
        }

        return false;
    }
}