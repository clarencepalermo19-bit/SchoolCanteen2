package com.mycompany.Controller;

import com.mycompany.Model.Product;
import com.mycompany.Product.ComboItem;
import com.mycompany.Product.ProductDAO;
import com.mycompany.StockIn.StockInDAO;
import com.mycompany.View.SchoolCanteen1;
import java.awt.event.ActionEvent;
import java.awt.event.ActionListener;
import javax.swing.JComboBox;
import javax.swing.JOptionPane;
import javax.swing.table.DefaultTableModel;

public class ProductController {

    private SchoolCanteen1 sc; // main form (View)

    public ProductController(SchoolCanteen1 sc) {

        this.sc = sc;

        // PRODUCT ID AND STOCK STATUS ARE READ-ONLY (generated by MySQL)
        sc.jTextField1.setEditable(false);
        sc.jTextField7.setEditable(false);

        // LOAD CATEGORY AND SUPPLIER COMBO BOXES
        ProductDAO.loadCategories(sc.jComboBox1);
        ProductDAO.loadSuppliers(sc.jComboBox2);

        // BUTTON LISTENERS (one listener object for all buttons)
        AllActions actions = new AllActions();  //Object
        sc.btnCreate.addActionListener(actions);
        sc.btnRead.addActionListener(actions);
        sc.btnUpdate.addActionListener(actions);
        sc.btnDelete.addActionListener(actions);
        sc.btnClear.addActionListener(actions);

        // TABLE ROW SELECTION:
        sc.jTable1.getSelectionModel().addListSelectionListener(e -> { //addListSelectionListener ang "manugpamati". Kon may row nga ginklik ka, mag-run ang code sa sulod.
                                                                       //e -> ang lambda, shortcut nga pagsulat sang "kon may mahitabo, himua ini".
            if (!e.getValueIsAdjusting()) {   // kon tapos na ang pagpili sang row (indi na ginabag-o), mag-run ang code sa idalom

                int row = sc.jTable1.getSelectedRow(); 

                if (row >= 0) {

                    String id = sc.jTable1.getValueAt(row, 0).toString();

                    Product p = ProductDAO.getByID(id);

                    if (p != null) {
                        sc.jTextField1.setText(p.getProductID());
                        sc.jTextField2.setText(p.getProductName());

                        selectComboByID(sc.jComboBox1, p.getCategoryID());
                        selectComboByID(sc.jComboBox2, p.getSupplierID());

                        sc.jTextField5.setText(p.getUnitPrice());
                        sc.jTextField6.setText(p.getQuantity());
                        sc.jTextField7.setText(p.getStockStatus());
                    }
                }
            }
        });

        // SHOW PRODUCTS WHEN THE APP STARTS
        refreshTable();
    }

    // =========================================
    // SELECT COMBO BOX ITEM USING DATABASE ID
    // =========================================
    private void selectComboByID(JComboBox<ComboItem> combo, String id) {

        if (id == null || id.trim().isEmpty()) {
            combo.setSelectedIndex(-1);
            return;
        }

        for (int i = 0; i < combo.getItemCount(); i++) {

            ComboItem item = combo.getItemAt(i); //Ang getItemAt(i) nagakuha sang item sa dropdown sa position nga i.

            if (item.getId() == Integer.parseInt(id)) {
                combo.setSelectedIndex(i);
                return;
            }
        }

        combo.setSelectedIndex(-1);   // not found
    }

    // =========================================
    // GET SELECTED DATABASE ID ("" if default item is selected)
    // =========================================
    private String getSelectedID(JComboBox<ComboItem> combo) {

        ComboItem item = (ComboItem) combo.getSelectedItem();

        if (item == null || item.getId() == 0) {
            return "";
        }

        return String.valueOf(item.getId());
    }

    // =========================================
    // GET PRODUCT DATA FROM FORM
    // =========================================
    private Product getProductFromFields() {

        Product p = new Product();

        p.setProductID(sc.jTextField1.getText().trim());
        p.setProductName(sc.jTextField2.getText().trim());
        p.setCategoryID(getSelectedID(sc.jComboBox1));
        p.setSupplierID(getSelectedID(sc.jComboBox2));
        p.setUnitPrice(sc.jTextField5.getText().trim());
        p.setQuantity(sc.jTextField6.getText().trim());

        // Stock status is automatically generated by MySQL.

        return p;
    }

    // =========================================
    // VALIDATE PRODUCT INFORMATION
    // =========================================
    private boolean validateFields() {

        String name = sc.jTextField2.getText().trim();
        String categoryID = getSelectedID(sc.jComboBox1);
        String supplierID = getSelectedID(sc.jComboBox2);
        String price = sc.jTextField5.getText().trim();
        String qty = sc.jTextField6.getText().trim();

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(sc, "Please enter Product Name.");
            sc.jTextField2.requestFocus();
            return false;
        }

        if (categoryID.isEmpty()) {
            JOptionPane.showMessageDialog(sc, "Please select a Category.");
            sc.jComboBox1.requestFocus();
            return false;
        }

        if (supplierID.isEmpty()) {
            JOptionPane.showMessageDialog(sc, "Please select a Supplier.");
            sc.jComboBox2.requestFocus();
            return false;
        }

        if (price.isEmpty()) {
            JOptionPane.showMessageDialog(sc, "Please enter Unit Price.");
            sc.jTextField5.requestFocus();
            return false;
        }

        if (qty.isEmpty()) {
            JOptionPane.showMessageDialog(sc, "Please enter Quantity.");
            sc.jTextField6.requestFocus();
            return false;
        }

        try {

            double priceValue = Double.parseDouble(price);
            int quantityValue = Integer.parseInt(qty);

            if (priceValue < 0 || quantityValue < 0) {
                JOptionPane.showMessageDialog(sc,
                        "Price and Quantity cannot be negative.");
                return false;
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(sc,
                    "Please enter valid numbers for Unit Price and Quantity.");
            return false;
        }

        return true;
    }

    // =========================================
    // REFRESH JTABLE
    // =========================================
    private void refreshTable() {
        sc.jTable1.setModel(ProductDAO.getTableData());
    }

    // =========================================
    // SHOW ONLY THE ROW WITH THE GIVEN PRODUCT ID
    // =========================================
    private void showOnlyRow(String id) {

        DefaultTableModel model = (DefaultTableModel) sc.jTable1.getModel();

        for (int i = model.getRowCount() - 1; i >= 0; i--) {
            if (!model.getValueAt(i, 0).toString().equals(id)) {
                model.removeRow(i);
            }
        }
    }

    // =========================================
    // CLEAR ALL FIELDS
    // =========================================
    private void clearFields() {

        sc.jTextField1.setText("");
        sc.jTextField2.setText("");

        sc.jComboBox1.setSelectedIndex(0);
        sc.jComboBox2.setSelectedIndex(0);

        sc.jTextField5.setText("");
        sc.jTextField6.setText("");
        sc.jTextField7.setText("");

        sc.jTable1.clearSelection();
    }

    // =========================================
    // RELOAD PRODUCT DROPDOWNS IN STOCK IN / STOCK OUT TABS
    // =========================================
    @SuppressWarnings("unchecked")
    private void reloadStockCombos() {
        StockInDAO.loadProducts((JComboBox<ComboItem>) (JComboBox<?>) sc.cmbProduct);
        StockInDAO.loadProducts((JComboBox<ComboItem>) (JComboBox<?>) sc.cmbProductOut);
    }

    // =========================================
    // BUTTON ACTIONS
    // =========================================
    class AllActions implements ActionListener {

        @Override
        public void actionPerformed(ActionEvent e) {

            Object source = e.getSource();

            // =================================
            // CREATE PRODUCT
            // =================================
            if (source == sc.btnCreate) {

                if (!validateFields()) {
                    return;
                }

                // NEW: block CREATE if the product name already exists
                String newName = sc.jTextField2.getText().trim();

                if (ProductDAO.nameExists(newName, "")) {
                    JOptionPane.showMessageDialog(sc,
                            "Product name already exists!");
                    sc.jTextField2.requestFocus();
                    return;   // stop here, nothing is saved
                }

                Product p = getProductFromFields();

                if (ProductDAO.save(p)) {

                    JOptionPane.showMessageDialog(sc,
                            "Product saved successfully!");

                    refreshTable();
                    clearFields();
                    reloadStockCombos();

                } else {
                    JOptionPane.showMessageDialog(sc,
                            "Unable to save product. Check your database connection, Category and Supplier.");
                }
            }

            // =================================
            // READ PRODUCT
            // =================================
            else if (source == sc.btnRead) {

                String id = sc.jTextField1.getText().trim();

                if (id.isEmpty()) {

                    refreshTable();   // no ID: show all products

                } else {

                    Product p = ProductDAO.getByID(id);

                    if (p != null) {
                        refreshTable();
                        showOnlyRow(id);
                    } else {
                        JOptionPane.showMessageDialog(sc,
                                "Product ID not found!");
                    }
                }
            }

            // =================================
            // UPDATE PRODUCT
            // =================================
            else if (source == sc.btnUpdate) {

                String id = sc.jTextField1.getText().trim();

                if (id.isEmpty()) {
                    JOptionPane.showMessageDialog(sc,
                            "Please select a product first.");
                    return;
                }

                if (!validateFields()) {
                    return;
                }

                // NEW: block UPDATE if ANOTHER product already has this name
                String newName = sc.jTextField2.getText().trim();

                if (ProductDAO.nameExists(newName, id)) {
                    JOptionPane.showMessageDialog(sc,
                            "Another product with this name already exists!");
                    sc.jTextField2.requestFocus();
                    return;
                }

                Product p = getProductFromFields();

                if (ProductDAO.update(p)) {

                    JOptionPane.showMessageDialog(sc,
                            "Product updated successfully!");

                    refreshTable();
                    clearFields();
                    reloadStockCombos();

                } else {
                    JOptionPane.showMessageDialog(sc,
                            "Unable to update product. Check the selected Category and Supplier.");
                }
            }

            // =================================
            // DELETE PRODUCT
            // =================================
            else if (source == sc.btnDelete) {

                String id = sc.jTextField1.getText().trim();

                if (id.isEmpty()) {
                    JOptionPane.showMessageDialog(sc,
                            "Please select a product first.");
                    return;
                }

                int confirm = JOptionPane.showConfirmDialog(
                        sc,
                        "Are you sure you want to delete this product?",
                        "Confirm Delete",
                        JOptionPane.YES_NO_OPTION
                );

                if (confirm == JOptionPane.YES_OPTION) {

                    if (ProductDAO.delete(id)) {

                        JOptionPane.showMessageDialog(sc,
                                "Product deleted successfully!");

                        refreshTable();
                        clearFields();
                        reloadStockCombos();

                    } else {
                        JOptionPane.showMessageDialog(sc,
                                "Unable to delete product. It may have existing Stock In or Stock Out records.");
                    }
                }
            }

            // =================================
            // CLEAR FORM
            // =================================
            else if (source == sc.btnClear) {

                clearFields();
                refreshTable();
            }
        }
    }
}